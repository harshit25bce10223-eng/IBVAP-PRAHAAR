"""Export replay scores by executing the canonical pure backend risk functions.

Uses checked-in Settings defaults, not a running deployment's environment. AST
loading isolates the pure scorer from optional FastAPI/Pydantic dependencies;
no risk formulas are reimplemented here. Regenerate after changing backend rules.
"""
import ast
import hashlib
import json
from pathlib import Path
from types import SimpleNamespace

ROOT = Path(__file__).resolve().parents[1]
config_path = ROOT / 'app/core/config.py'
config_tree = ast.parse(config_path.read_text(encoding='utf-8'))
settings_class = next(node for node in config_tree.body if isinstance(node, ast.ClassDef) and node.name == 'Settings')
defaults = {}
for node in settings_class.body:
    if isinstance(node, ast.AnnAssign) and isinstance(node.target, ast.Name) and node.target.id.startswith(('RISK_', 'SEVERITY_')):
        defaults[node.target.id] = ast.literal_eval(node.value)
settings = SimpleNamespace(**defaults)

def pure_module(path, namespace):
    tree = ast.parse(path.read_text(encoding='utf-8'))
    tree.body = [node for node in tree.body if not isinstance(node, (ast.Import, ast.ImportFrom))]
    exec(compile(tree, str(path), 'exec'), namespace)
    return SimpleNamespace(**namespace)

factor_path = ROOT / 'app/domain/risk/risk_factors.py'
severity_path = ROOT / 'app/domain/risk/severity.py'
engine_path = ROOT / 'app/domain/risk/risk_engine.py'
factors = pure_module(factor_path, {'settings': settings})
severity = pure_module(severity_path, {'settings': settings})
from dataclasses import dataclass, field
from typing import Any
engine = pure_module(engine_path, {
    'settings': settings, 'risk_factors': factors, 'Severity': str,
    'severity_for_score': severity.severity_for_score, 'dataclass': dataclass,
    'field': field, 'Any': Any, 'InvalidConfidenceError': ValueError,
    'InvalidObjectTypeError': ValueError, 'InvalidBBoxError': ValueError,
})
result = {}
for key, confidence in [('clear', .94), ('degraded', .72)]:
    inputs = dict(object_type='HUMAN', zone_crossed=True, is_night=True,
                  multi_camera_confirmed=False, confidence=confidence,
                  reliability='MEDIUM', evidence='EVT-2291 / TRK-017 / replay fixture')
    result[key] = {'inputs': inputs, 'result': engine.calculate_risk(**inputs).to_dict()}
fixture = {
    'provenance': 'Canonical backend calculate_risk, checked-in Settings defaults; REPLAY TEST',
    'sourceHashes': {str(path.relative_to(ROOT)).replace('\\', '/'): hashlib.sha256(path.read_bytes()).hexdigest()
                     for path in [config_path, factor_path, severity_path, engine_path]},
    'cases': result,
}
target = ROOT.parent / 'ibvap-frontend/src/components/demo/backendRiskReplay.ts'
target.write_text('// Generated by ibvap-backend/scripts/export_master_demo_fixtures.py\n'
                  'export const backendRiskReplay = ' + json.dumps(fixture, indent=2) + ' as const\n', encoding='utf-8')
print('Exported canonical backend replay scores:', {key: value['result']['risk_score'] for key, value in result.items()})
